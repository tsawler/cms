// Command build bundles the editor's ES-module source (editor/src) into
// the single committed artifact editor/editor.js that go:embed ships.
//
// It lives in its own Go module so esbuild never appears in the cms
// module's dependency graph — consumers of the CMS need only the Go
// toolchain and never run this. Contributors run it via:
//
//	go generate ./editor        (from the repo root)
//
// or directly, with a watch mode for the edit-refresh loop:
//
//	go run -C editor/build . -watch
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/evanw/esbuild/pkg/api"
)

func main() {
	watch := flag.Bool("watch", false, "rebuild on every source change")
	flag.Parse()

	// Paths are anchored to this file's module directory (editor/build)
	// so the tool works from any working directory go:generate uses.
	root, err := os.Getwd()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	// Allow running from the repo root or editor/ as well as editor/build.
	for _, probe := range []string{".", "editor/build", "build"} {
		if _, err := os.Stat(filepath.Join(root, probe, "build.go")); err == nil {
			root = filepath.Join(root, probe)
			break
		}
	}

	opts := api.BuildOptions{
		EntryPoints: []string{filepath.Join(root, "..", "src", "main.js")},
		Outfile:     filepath.Join(root, "..", "editor.js"),
		Bundle:      true,
		Write:       true,
		// One classic-script IIFE, matching how the file has always been
		// served; kept readable (not minified) so the committed artifact
		// is reviewable and debuggable as-is.
		Format:            api.FormatIIFE,
		Target:            api.ES2018,
		MinifyWhitespace:  false,
		MinifyIdentifiers: false,
		MinifySyntax:      false,
		// CSS imported from .js files is bundled as plain text.
		Loader:   map[string]api.Loader{".css": api.LoaderText},
		LogLevel: api.LogLevelInfo,
		Banner: map[string]string{
			"js": "/* Generated by editor/build — edit editor/src/*, then run: go generate ./editor */",
		},
	}

	if *watch {
		ctx, ctxErr := api.Context(opts)
		if ctxErr != nil {
			fmt.Fprintln(os.Stderr, ctxErr.Error())
			os.Exit(1)
		}
		if err := ctx.Watch(api.WatchOptions{}); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		fmt.Println("watching editor/src — Ctrl-C to stop")
		select {}
	}

	if result := api.Build(opts); len(result.Errors) > 0 {
		os.Exit(1)
	}
}
